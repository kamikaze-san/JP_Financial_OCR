import os
import sys
import time
import json
import ollama

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

from solution1.models import RawDocumentTree
from solution1.baseline_data import get_baseline_raw_tree
from solution1.normalizer import normalize_tree
from solution1.validator import AccountingValidator
from solution1.vlm_interface import parse_vlm_response
from run_benchmark import BENCHMARK_PROMPT

def run_pure_autonomous_loop():
    print("=" * 70)
    print("   TESTING PURE AUTONOMOUS ARITHMETIC FEEDBACK LOOP (NO HUMAN HINTS)   ")
    print("=" * 70)

    # 1. Use initial 150 DPI image (where row 26 was missed in Pass 1)
    image_path = "solution1/rendered_images_150dpi/balance_sheet_after_correction_page_1.png"
    pass1_path = "benchmark_results/qwen3-vl_4b-instruct/pass1_raw_output.json"
    
    if os.path.exists(pass1_path):
        print(f"\n[Step 1] Loading initial 150 DPI Pass 1 output from {pass1_path}...")
        with open(pass1_path, "r", encoding="utf-8") as f:
            pass1_text = f.read()
    else:
        print("\n[Step 1] Running Pass 1 on 150 DPI image with qwen3-vl:4b-instruct...")
        resp1 = ollama.chat(
            model="qwen3-vl:4b-instruct",
            messages=[{"role": "user", "content": BENCHMARK_PROMPT, "images": [image_path]}],
            format="json",
            options={"num_ctx": 16384, "num_predict": 4096, "temperature": 0.0}
        )
        pass1_text = resp1['message']['content']

    # Evaluate Pass 1
    pred_raw1 = parse_vlm_response(pass1_text)
    pred_norm1 = normalize_tree(pred_raw1)
    validator = AccountingValidator()
    report1 = validator.validate(pred_norm1)
    
    print("-" * 50)
    print(f"Pass 1 Validation Status: {'[PASSED]' if report1.is_valid else '[FAILED AS EXPECTED]'}")
    print(f"Pass 1 Equations: {report1.passed_equations} / {report1.total_equations_tested}")
    print(f"Failures Count:   {len(report1.failures)}")
    print("-" * 50)

    # 2. Generate PURE PROGRAMMATIC FEEDBACK (No human input, zero leaked row names)
    print("\n[Step 2] Programmatically generating feedback from validator.py...")
    auto_feedback_prompt = validator.generate_arithmetic_feedback(
        report1, 
        unit_raw=pred_norm1.unit_raw, 
        unit_scale=pred_norm1.unit_multiplier
    )
    
    print("\n--- EXACT PROMPT GENERATED BY PYTHON CODE (ZERO HUMAN HINTS) ---")
    print(auto_feedback_prompt)
    print("-----------------------------------------------------------------\n")

    # 3. Send autonomous feedback to model in Pass 2
    print("[Step 3] Sending autonomous feedback back to qwen3-vl:4b-instruct...")
    messages = [
        {"role": "user", "content": BENCHMARK_PROMPT, "images": [image_path]},
        {"role": "assistant", "content": pass1_text},
        {"role": "user", "content": auto_feedback_prompt}
    ]

    t0 = time.time()
    resp2 = ollama.chat(
        model="qwen3-vl:4b-instruct",
        messages=messages,
        format="json",
        options={"num_ctx": 16384, "num_predict": 4096, "temperature": 0.0}
    )
    latency2 = time.time() - t0
    print(f"Pass 2 completed in {latency2:.1f}s")

    pass2_text = resp2['message']['content']
    out_dir = "benchmark_results/qwen3-vl_4b-instruct"
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "pass2_pure_autonomous_output.json"), "w", encoding="utf-8") as f:
        f.write(pass2_text)

    # 4. Evaluate Pass 2
    print("\n[Step 4] Running MECE Accounting Validator on Pass 2 Output...")
    pred_raw2 = parse_vlm_response(pass2_text)
    pred_norm2 = normalize_tree(pred_raw2)
    report2 = validator.validate(pred_norm2)

    print("=" * 70)
    print(f"PASS 2 AUTONOMOUS RESULT: {'[100% PASSED]' if report2.is_valid else '[FAILED]'}")
    print(f"Equations Passed: {report2.passed_equations} / {report2.total_equations_tested}")
    print(f"Failed Equations: {report2.failed_equations}")
    
    # Check if any new row was inserted
    initial_rows = {r.account_raw for r in pred_raw1.rows}
    pass2_rows = {r.account_raw for r in pred_raw2.rows}
    new_rows = pass2_rows - initial_rows
    if new_rows:
        print(f"Autonomously Discovered New Rows: {new_rows}")
        for r in pred_raw2.rows:
            if r.account_raw in new_rows:
                print(f"  * {r.account_raw}: Values={r.values}, Role={r.role}")
    else:
        print("No new row names were inserted.")

    # Check comparison with Gold Answer Key
    gold_raw = get_baseline_raw_tree()
    gold_norm = normalize_tree(gold_raw)
    dates = ["2025-03-31", "2026-03-31"]
    matched = sum(1 for p_it, g_it in zip(pred_norm2.items, gold_norm.items) for d in dates if p_it.normalized_values.get(d) == g_it.normalized_values.get(d))
    total = len(gold_norm.items) * len(dates)
    print(f"Exact Cell Match vs Gold Key: {matched} / {total} ({matched/total*100:.2f}%)")
    print("=" * 70)

if __name__ == "__main__":
    run_pure_autonomous_loop()
