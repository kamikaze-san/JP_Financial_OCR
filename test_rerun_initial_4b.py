import os
import sys
import time
import json
import ollama

if sys.stdout.encoding != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8')

from solution1.models import RawDocumentTree
from solution1.normalizer import normalize_tree
from solution1.validator import AccountingValidator
from solution1.auto_feedback import generate_automated_audit_feedback
from solution1.vlm_interface import parse_vlm_response
from run_benchmark import BENCHMARK_PROMPT

def rerun_initial_4b():
    print("=" * 70)
    print("   RE-RUNNING INITIAL 4B RUN WITH ZERO-LEAKAGE AUTOMATED FEEDBACK   ")
    print("=" * 70)

    image_path = "solution1/rendered_images_150dpi/balance_sheet_after_correction_page_1.png"
    pass1_path = "benchmark_results/qwen3-vl_4b-instruct/pass1_raw_output.json"

    # 1. Load the initial Pass 1 output (which had 19/20 equations)
    with open(pass1_path, "r", encoding="utf-8") as f:
        pass1_text = f.read()

    pred_raw1 = parse_vlm_response(pass1_text)
    pred_norm1 = normalize_tree(pred_raw1)
    validator = AccountingValidator()
    report1 = validator.validate(pred_norm1)

    print(f"\n[Pass 1 Baseline Status]: {report1.passed_equations} / {report1.total_equations_tested} equations passed (19/20)")
    
    # 2. Generate pure algorithmic feedback
    auto_feedback = generate_automated_audit_feedback(pred_norm1, report1)
    
    print("\n--- PURE ALGORITHMIC FEEDBACK GENERATED BY PYTHON ---")
    print(auto_feedback)
    print("----------------------------------------------------\n")

    # 3. Send autonomous feedback to qwen3-vl:4b-instruct on the 150 DPI image
    print("[Pass 2] Sending pure algorithmic feedback to qwen3-vl:4b-instruct (150 DPI)...")
    messages = [
        {"role": "user", "content": BENCHMARK_PROMPT, "images": [image_path]},
        {"role": "assistant", "content": pass1_text},
        {"role": "user", "content": auto_feedback}
    ]

    t0 = time.time()
    resp2 = ollama.chat(
        model="qwen3-vl:4b-instruct",
        messages=messages,
        format="json",
        options={"num_ctx": 16384, "num_predict": 4096, "temperature": 0.0}
    )
    latency2 = time.time() - t0
    print(f"Pass 2 finished in {latency2:.1f}s")

    pass2_text = resp2['message']['content']
    with open("benchmark_results/qwen3-vl_4b-instruct/pass2_rerun_clean_feedback.json", "w", encoding="utf-8") as f:
        f.write(pass2_text)

    # 4. Evaluate Pass 2
    pred_raw2 = parse_vlm_response(pass2_text)
    pred_norm2 = normalize_tree(pred_raw2)
    report2 = validator.validate(pred_norm2)

    print("\n" + "=" * 70)
    print(f"PASS 2 CLEAN RE-RUN RESULT: {'[PASSED 100%]' if report2.is_valid else '[FAILED]'}")
    print(f"Equations Passed: {report2.passed_equations} / {report2.total_equations_tested}")
    
    # Print what the model changed for 建設仮勘定
    item_target = next((it for it in pred_norm2.items if "建設" in it.account_jp), None)
    if item_target:
        print(f"Extracted values for '建設仮勘定': {item_target.raw_values}")
    print("=" * 70)

if __name__ == "__main__":
    rerun_initial_4b()
